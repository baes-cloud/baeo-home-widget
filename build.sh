#!/usr/bin/env bash
# Builds baeo-widgets.apk without Gradle. HA address/token come from local.properties (not in source).
# Signing: KS (keystore path, default baeo.keystore), KS_PASS and KS_ALIAS in the environment, or in local.properties
# as ks.file / ks.pass / ks.alias. Without a password you get build/aligned.apk, unsigned.
set -euo pipefail
cd "$(dirname "$0")"
SDK="${ANDROID_HOME:-$HOME/Android/Sdk}"
BT="$SDK/build-tools/35.0.0"
JAR="$SDK/platforms/android-34/android.jar"
JAVA_HOME="${JAVA_HOME:-$HOME/.jdks/jdk-21.0.12.1+1}"
export JAVA_HOME PATH="$JAVA_HOME/bin:$PATH"
prop() { grep -m1 "^$1=" local.properties 2>/dev/null | cut -d= -f2- || true; }

rm -rf build && mkdir -p build/gen/com/baeo/widgets build/classes build/dex
python3 - "$(prop ha.url)" "$(prop ha.token)" "$(prop agent.url)" "$(prop agent.token)" "$(prop ha.cloud_url)" "$(prop agent.cloud_url)" "$(prop cf.id)" "$(prop cf.secret)" "$(prop calendar)" "$(prop agent.page_url)" > build/gen/com/baeo/widgets/Secrets.java <<'PY'
import json, sys
print("package com.baeo.widgets;\n/** Generated by build.sh from local.properties. */\nfinal class Secrets {\n"
      f"    static final String HA_URL = {json.dumps(sys.argv[1])};\n    static final String HA_TOKEN = {json.dumps(sys.argv[2])};\n"
      f"    static final String AGENT_URL = {json.dumps(sys.argv[3])};\n    static final String AGENT_TOKEN = {json.dumps(sys.argv[4])};\n"
      f"    static final String HA_CLOUD_URL = {json.dumps(sys.argv[5])};\n    static final String AGENT_CLOUD_URL = {json.dumps(sys.argv[6])};\n"
      f"    static final String CF_ID = {json.dumps(sys.argv[7])};\n    static final String CF_SECRET = {json.dumps(sys.argv[8])};\n"
      f"    static final String CALENDAR = {json.dumps(sys.argv[9] or 'calendar.work')};\n    static final String AGENT_PAGE_URL = {json.dumps(sys.argv[10] or 'about:blank')};\n}}")
PY
"$BT/aapt2" compile --dir res -o build/res.zip
"$BT/aapt2" link -o build/unsigned.apk -I "$JAR" --manifest AndroidManifest.xml -A assets --java build/gen build/res.zip
javac -nowarn -source 17 -target 17 -classpath "$JAR" -d build/classes $(find src build/gen -name '*.java')
"$BT/d8" --release --min-api 31 --lib "$JAR" --output build/dex $(find build/classes -name '*.class')
(cd build/dex && zip -q ../unsigned.apk classes.dex)
"$BT/zipalign" -f 4 build/unsigned.apk build/aligned.apk

KS="${KS:-$(prop ks.file)}"; KS="${KS:-baeo.keystore}"
KS_PASS="${KS_PASS:-$(prop ks.pass)}"
KS_ALIAS="${KS_ALIAS:-$(prop ks.alias)}"
if [ -n "$KS_PASS" ]; then
  "$BT/apksigner" sign --ks "$KS" --ks-pass "pass:$KS_PASS" ${KS_ALIAS:+--ks-key-alias "$KS_ALIAS"} --out baeo-widgets.apk build/aligned.apk
  echo "signed: baeo-widgets.apk ($KS)"
else
  echo "unsigned: build/aligned.apk (no ks.pass)"
fi
